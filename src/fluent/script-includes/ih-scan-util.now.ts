import { ScriptInclude } from '@servicenow/sdk/core'

// Shared helper for the scan checks: the "custom" rule (IH-003, IH-009 to IH-015, IH-018, IH-020),
// the line-by-line reporting of regex matches in scripts, and the baseline checks (IH-024 to IH-028).
export const ihScanUtil = ScriptInclude({
    $id: Now.ID['ih-scan-util'],
    name: 'IHScanUtil',
    apiName: 'x_bits2_inst_hlth.IHScanUtil',
    accessibleFrom: 'package_private',
    active: true,
    description:
        'Helper for the Instance Health scan checks. isCustom() decides whether a record is customer code; checkScript() and reportLines() report every matching script line in finding_details.',
    script: `var IHScanUtil = Class.create();
IHScanUtil.prototype = {
    APP_SCOPE: 'x_bits2_inst_hlth',
    MAX_LINES: 20,
    MAX_LINE_LENGTH: 200,
    MAX_DETAILS: 7900,
    SKIP_TABLES: ['scan_column_type_check', 'scan_script_only_check', 'scan_table_check', 'scan_linter_check',
        'sys_script_execution_history', 'sys_update_xml', 'sys_update_version'],
    // Records generated by the platform, never custom code (user decision 2026-11-06): GAF scheduled
    // scripts are created by "system" in the Global package, OneExtend mappings by app configuration.
    GENERATED_TABLES: ['sn_gaf_sysauto_script', 'sys_one_extend_resource_mapping'],

    initialize: function() {
        this._updateCache = {};
        this._ownAppId = null;
    },

    // Custom = record from a customer scoped app (not this app), or a global record with a
    // customer update (sys_update_xml, application global). Plugins, store apps and the base
    // system never count. Agreed with the user 2026-11-05 (IH-003) and 2026-11-06 (batch 2).
    isCustom: function(gr) {
        if (!gr || !gr.isValidRecord() || !gr.isValidField('sys_package')) return false;
        if (this.GENERATED_TABLES.indexOf(gr.getRecordClassName()) > -1) return false;
        var pkg = gr.getValue('sys_package');
        if (!pkg) return false;
        if (pkg == 'global') return this._hasGlobalCustomerUpdate(gr.getValue('sys_update_name'));
        if (pkg == this._getOwnAppId()) return false;
        return gr.sys_package.sys_class_name + '' == 'sys_app';
    },

    // ColumnTypeCheck helper: report all lines of columnValue that match regex, for custom records only
    checkScript: function(engine, current, columnValue, regex) {
        if (!columnValue || !this._test(regex, columnValue)) return;
        if (this.SKIP_TABLES.indexOf(current.getRecordClassName()) > -1) return;
        if (!this.isCustom(current)) return;
        var lines = this.matchingLines(columnValue, regex);
        if (lines.length > 0) this.reportLines(engine, current, lines, '');
    },

    // Every line that matches regex after comments are removed, as "line N: <code>"
    matchingLines: function(text, regex) {
        var original = (text + '').split('\\n');
        var clean = this.stripComments(text + '').split('\\n');
        var out = [];
        for (var i = 0; i < clean.length; i++) {
            if (!this._test(regex, clean[i])) continue;
            var code = (original[i] || '').replace(/^\\s+|\\s+$/g, '');
            if (code.length > this.MAX_LINE_LENGTH) code = code.substring(0, this.MAX_LINE_LENGTH) + '...';
            out.push('line ' + (i + 1) + ': ' + code);
        }
        return out;
    },

    // Remove block and line comments but keep the line breaks, so line numbers stay correct.
    // "//" after ":" is kept (URLs such as https://...).
    stripComments: function(text) {
        var noBlocks = text.replace(/\\/\\*[\\s\\S]*?\\*\\//g, function(match) {
            return match.replace(/[^\\n]/g, '');
        });
        return noBlocks.replace(/(^|[^:\\\\])\\/\\/.*$/gm, '$1');
    },

    reportLines: function(engine, record, lines, intro) {
        var shown = lines.slice(0, this.MAX_LINES);
        var details = (intro ? intro + '\\n' : '') + shown.join('\\n');
        if (lines.length > shown.length)
            details += '\\n... and ' + (lines.length - shown.length) + ' more line(s)';
        engine.finding.setCurrentSource(record);
        engine.finding.setValue('finding_details', details.substring(0, this.MAX_DETAILS));
        engine.finding.increment();
    },

    // IH-038, IH-059: reasons why a script condition is complex (user decision 2026-11-06:
    // longer than 200 characters, a query, a statement separator or a function). [] if simple.
    conditionComplexity: function(condition) {
        var reasons = [];
        if (!condition) return reasons;
        if (condition.length > 200) reasons.push(condition.length + ' characters');
        if (/\\bGlide(Record|Aggregate)/.test(condition)) reasons.push('database query');
        if (condition.indexOf(';') > -1) reasons.push('several statements');
        if (/\\bfunction\\b/.test(condition)) reasons.push('function');
        return reasons;
    },

    // IH-047, IH-048: resolve a scheduled job's run_as value. It is a sys_user reference, but some
    // jobs hold a user name ("admin") or an internal platform user ("system", "maint").
    // Returns { state: 'empty' | 'internal' | 'missing' | 'inactive' | 'active', user: GlideRecord or null }
    // 'empty' (no value, or only blanks): the job has no Run as user, which is not a finding (2026-11-12)
    resolveRunAs: function(value) {
        if (value === null || value === undefined || (value + '').replace(/^\\s+|\\s+$/g, '') == '') return { state: 'empty', user: null };
        if (value == 'system' || value == 'maint') return { state: 'internal', user: null };
        var user = new GlideRecord('sys_user');
        if (!user.get(value)) {
            user = new GlideRecord('sys_user');
            if (!user.get('user_name', value)) return { state: 'missing', user: null };
        }
        return { state: user.active == true ? 'active' : 'inactive', user: user };
    },

    // IH-037: lines of a business rule script that pass current to a script include function which calls
    // update() on the parameter that receives current. Only the function that is called is searched:
    // new X(current) -> initialize, new X().m(current) and X.m(current) -> m (2026-11-12, was the whole include).
    // Returns "line N: <code> -> script include X.m: <param>.update() (line L)"
    findIndirectCurrentUpdates: function(script) {
        var lines = this.stripComments(script + '').split('\\n');
        var original = (script + '').split('\\n');
        var passesCurrent = /\\([^()]*\\bcurrent\\b(?!\\s*\\.)/;
        var out = [];
        for (var i = 0; i < lines.length; i++) {
            if (!passesCurrent.test(lines[i])) continue;
            var calls = this._includeCalls(lines[i]);
            for (var c = 0; c < calls.length; c++) {
                var indexes = [];
                for (var a = 0; a < calls[c].args.length; a++)
                    if (calls[c].args[a] == 'current') indexes.push(a);
                if (indexes.length == 0) continue;
                var updated = this._includeUpdatesParameter(calls[c].name, calls[c].method, indexes);
                if (updated)
                    out.push('line ' + (i + 1) + ': ' + (original[i] || '').replace(/^\\s+|\\s+$/g, '').substring(0, this.MAX_LINE_LENGTH) +
                        ' -> script include ' + calls[c].name + '.' + calls[c].method + ': ' + updated);
            }
        }
        return out;
    },

    // Calls of script includes in one line: { name, method, args } for new X(args), new X().m(args) and X.m(args)
    _includeCalls: function(line) {
        var calls = [];
        var ctor = /\\bnew\\s+(?:[A-Za-z_$][\\w$]*\\.)*([A-Za-z_$][\\w$]*)\\s*\\(/g;
        var m;
        while ((m = ctor.exec(line)) !== null) {
            var parsed = this._callArgs(line, m.index + m[0].length - 1);
            if (!parsed) continue;
            calls.push({ name: m[1], method: 'initialize', args: parsed.args });
            var chain = /^\\s*\\.\\s*([A-Za-z_$][\\w$]*)\\s*\\(/.exec(line.substring(parsed.end + 1));
            if (chain) {
                var chainParsed = this._callArgs(line, parsed.end + chain[0].length);
                if (chainParsed) calls.push({ name: m[1], method: chain[1], args: chainParsed.args });
            }
        }
        var stat = /\\b([A-Z][\\w$]*)\\s*\\.\\s*([A-Za-z_$][\\w$]*)\\s*\\(/g;
        while ((m = stat.exec(line)) !== null) {
            var staticParsed = this._callArgs(line, m.index + m[0].length - 1);
            if (staticParsed) calls.push({ name: m[1], method: m[2], args: staticParsed.args });
        }
        return calls;
    },

    // Arguments of the call whose opening parenthesis is at text[open]: { args: [trimmed strings], end: index of ")" }
    _callArgs: function(text, open) {
        var depth = 0;
        var quote = '';
        var start = open + 1;
        var args = [];
        for (var i = open; i < text.length; i++) {
            var ch = text.charAt(i);
            if (quote) {
                if (ch == '\\\\') i++;
                else if (ch == quote) quote = '';
                continue;
            }
            if (ch == "'" || ch == '"') quote = ch;
            else if (ch == '(' || ch == '[' || ch == '{') depth++;
            else if (ch == ')' || ch == ']' || ch == '}') {
                depth--;
                if (depth == 0) {
                    var last = text.substring(start, i).replace(/^\\s+|\\s+$/g, '');
                    if (last || args.length > 0) args.push(last);
                    return { args: args, end: i };
                }
            } else if (ch == ',' && depth == 1) {
                args.push(text.substring(start, i).replace(/^\\s+|\\s+$/g, ''));
                start = i + 1;
            }
        }
        return null;
    },

    // Index of the "}" that closes the "{" at code[open], -1 if not found
    _matchBrace: function(code, open) {
        var depth = 0;
        var quote = '';
        for (var i = open; i < code.length; i++) {
            var ch = code.charAt(i);
            if (quote) {
                if (ch == '\\\\') i++;
                else if (ch == quote) quote = '';
                continue;
            }
            if (ch == "'" || ch == '"') quote = ch;
            else if (ch == '{') depth++;
            else if (ch == '}') {
                depth--;
                if (depth == 0) return i;
            }
        }
        return -1;
    },

    // The function "method" of a script: m: function(a, b) {...}, X.prototype.m = function(a) {...} or function m(a) {...}.
    // Returns { params, body, startLine } or null.
    _findFunction: function(code, method) {
        var name = method.replace(/\\$/g, '\\\\$');
        var patterns = [
            new RegExp('\\\\b' + name + '\\\\s*[:=]\\\\s*function\\\\s*[\\\\w$]*\\\\s*\\\\(([^)]*)\\\\)\\\\s*\\\\{'),
            new RegExp('\\\\bfunction\\\\s+' + name + '\\\\s*\\\\(([^)]*)\\\\)\\\\s*\\\\{')
        ];
        for (var p = 0; p < patterns.length; p++) {
            var m = patterns[p].exec(code);
            if (!m) continue;
            var open = m.index + m[0].length - 1;
            var end = this._matchBrace(code, open);
            if (end < 0) continue;
            var params = m[1].split(',');
            for (var i = 0; i < params.length; i++) params[i] = params[i].replace(/^\\s+|\\s+$/g, '');
            return { params: params, body: code.substring(open, end + 1), startLine: code.substring(0, open).split('\\n').length };
        }
        return null;
    },

    // Returns e.g. "record.update() (line 5)" if the function "method" of the script include calls update() on
    // the parameter at one of the given positions (the ones that receive current), '' otherwise. Cached.
    _includeUpdatesParameter: function(name, method, indexes) {
        if (!this._includeCache) this._includeCache = {};
        var key = name + '.' + method + '.' + indexes.join(',');
        if (this._includeCache.hasOwnProperty(key)) return this._includeCache[key];
        var result = '';
        var include = new GlideRecord('sys_script_include');
        include.addQuery('name', name);
        include.addActiveQuery();
        include.query();
        if (include.next()) {
            var fn = this._findFunction(this.stripComments(include.getValue('script') || ''), method);
            if (fn) {
                var params = [];
                for (var k = 0; k < indexes.length; k++)
                    if (indexes[k] < fn.params.length && /^[A-Za-z_$][\\w$]*$/.test(fn.params[indexes[k]])) params.push(fn.params[indexes[k]]);
                var bodyLines = fn.body.split('\\n');
                for (var i = 0; i < bodyLines.length && !result; i++) {
                    for (var p = 0; p < params.length; p++) {
                        if (new RegExp('\\\\b' + params[p].replace(/\\$/g, '\\\\$') + '\\\\s*\\\\.\\\\s*update\\\\s*\\\\(').test(bodyLines[i])) {
                            result = params[p] + '.update() (line ' + (fn.startLine + i) + ')';
                            break;
                        }
                    }
                }
            }
        }
        this._includeCache[key] = result;
        return result;
    },

    // IH-024 to IH-028: ServiceNow records that were changed, from the platform's own list
    // sys_metadata_customization (author_type ServiceNow = record shipped by ServiceNow)
    // skip (optional): function(record) returning true for records that must not be reported
    reportBaselineChanges: function(engine, classNames, skip) {
        var changed = new GlideRecord('sys_metadata_customization');
        changed.addQuery('author_type', 'ServiceNow');
        changed.addQuery('sys_metadata.sys_class_name', 'IN', classNames.join(','));
        changed.query();
        while (changed.next()) {
            var className = changed.sys_metadata.sys_class_name + '';
            var record = new GlideRecord(className);
            if (!record.isValid() || !record.get(changed.getValue('sys_metadata'))) continue;
            if (skip && skip(record)) continue;
            engine.finding.setCurrentSource(record);
            engine.finding.setValue('finding_details', 'ServiceNow ' + record.getClassDisplayValue() + ' changed by the customer (package ' +
                record.sys_package.getDisplayValue() + ', last updated ' + record.getValue('sys_updated_on') + ' by ' + record.getValue('sys_updated_by') + ')');
            engine.finding.increment();
        }
    },

    _test: function(regex, text) {
        regex.lastIndex = 0;
        return regex.test(text);
    },

    _hasGlobalCustomerUpdate: function(updateName) {
        if (!updateName) return false;
        if (this._updateCache.hasOwnProperty(updateName)) return this._updateCache[updateName];
        var upd = new GlideRecord('sys_update_xml');
        upd.addQuery('name', updateName);
        upd.addQuery('application', 'global');
        upd.setLimit(1);
        upd.query();
        var found = upd.hasNext();
        this._updateCache[updateName] = found;
        return found;
    },

    _getOwnAppId: function() {
        if (this._ownAppId === null) {
            var app = new GlideRecord('sys_scope');
            this._ownAppId = app.get('scope', this.APP_SCOPE) ? app.getUniqueValue() : '';
        }
        return this._ownAppId;
    },

    type: 'IHScanUtil'
};`,
})
